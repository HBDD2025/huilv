const assert=require('node:assert/strict');
const fs=require('node:fs');const path=require('node:path');
const rules=require('../web/recommend.js'),data=JSON.parse(fs.readFileSync(path.join(__dirname,'../data/cards.json')));
const v=data.valuations.defaults,ctx={location:'cn',channel:'direct',fee:0,foreignEligible:false,bofaBonus:false,ibpCapReached:false};
const result=(q,c=ctx)=>rules.recommend(data,q,c,v).results;
const card=(rows,id)=>rows.find(r=>r.card.id===id);
assert.equal(rules.classify('水费').scene,'utilities');assert.equal(rules.classify('电费').scene,'utilities');
assert.equal(rules.classify('餐饮').scene,'dining');assert.equal(rules.classify('支付宝电费').wallet,true);
assert.equal(rules.classify('完全未知词').scene,null);
for(const query of ['Trip.com','trip.com 机票','携程酒店','Booking.com','Expedia','Agoda','飞猪','去哪儿','同程'])assert.equal(rules.classify(query).scene,'thirdparty');
let rows=result('电费');assert.equal(rows.length,11);assert.equal(card(rows,'ibp').rate,1);assert.equal(card(rows,'atmos').rate,1);assert.equal(card(rows,'venturex').rate,2);
rows=result('电费',{...ctx,foreignEligible:true,bofaBonus:true});assert.ok(Math.abs(card(rows,'atmos').rate-3.3)<1e-10);
assert.equal(card(result('餐饮'),'aspire').rate,3);assert.equal(card(result('餐饮',{...ctx,location:'us'}),'aspire').rate,7);
assert.equal(card(result('宽带'),'ibp').rate,3);assert.equal(card(result('宽带',{...ctx,ibpCapReached:true}),'ibp').rate,1);
assert.equal(card(result('餐饮',{...ctx,channel:'wallet'}),'csp').rate,1);
assert.ok(Math.abs(card(result('电费',{...ctx,fee:3}),'venturex').low-(-1))<1e-10);
assert.ok(Math.abs(card(result('电费',{...ctx,fee:3}),'venturex').high-.4)<1e-10);
assert.equal(card(result('餐饮'),'savor').low,3);assert.equal(card(result('餐饮'),'savor').high,3);
assert.equal(card(result('凯悦'),'hyatt').rate,4);assert.equal(card(result('万豪'),'brilliant').rate,6);
assert.equal(card(result('酒店'),'ibp').rate,3);
rows=result('Trip.com 机票');assert.equal(rows.length,11);
assert.equal(card(rows,'csp').rate,1);assert.equal(card(rows,'ibp').rate,1);assert.equal(card(rows,'citi').rate,1);
assert.equal(card(rows,'aspire').rate,3);assert.equal(card(rows,'brilliant').rate,2);
assert.equal(card(rows,'venturex').rate,2);assert.equal(card(rows,'hyatt').rate,1);
assert.equal(card(rows,'citi').possibleThirdParty,3);
rows=result('Trip.com',{...ctx,travelCategoryConfirmed:true});
assert.equal(card(rows,'csp').rate,2);assert.equal(card(rows,'ibp').rate,3);assert.equal(card(rows,'citi').rate,3);
assert.equal(card(rows,'venturex').rate,2);assert.equal(card(rows,'brilliant').rate,2);
assert.equal(card(result('Trip.com',{...ctx,travelCategoryConfirmed:true,ibpCapReached:true}),'ibp').rate,1);
console.log('Passed: utilities, region, caps, wallet, fees, cashback, hotel brands and third-party travel category gating');
